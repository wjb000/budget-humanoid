"""URDF + MuJoCo MJCF + glTF export. Run after export.py logic (imports it)."""
import os, json, math, base64, numpy as np, trimesh
from export import *

STS_EFFORT = 2.94      # N m stall @12 V (30 kg.cm)
STS_RATED = 0.98       # N m rated (10 kg.cm)
STS_VEL = 4.72         # rad/s no-load (0.222 s/60 deg)
KP, KV = 20.0, 0.5     # MuJoCo position actuator gains (starting values, identify on hardware)
ARM, DAMP, FRIC = 0.02, 0.05, 0.03

LINK_COLOR = {'base': (0.78, 0.80, 0.84)}

def link_meshes(R):
    """printed mesh per link (link-local, metres)"""
    out = {}
    for lk, d in R['links'].items():
        o = R['origin'][lk]
        ms = []
        for pn in d['parts']:
            m = R['meshes'][pn].copy(); m.apply_translation(-o); m.apply_scale(1e-3); ms.append(m)
        out[lk] = trimesh.util.concatenate(ms)
    return out

def f(x): return ' '.join('%.6g' % v for v in x)

def inertia_tuple(I):
    return (I[0, 0], I[1, 1], I[2, 2], I[0, 1], I[0, 2], I[1, 2])

def children(J):
    k = {}
    for j in J: k.setdefault(j['parent'], []).append(j)
    return k

def write_sim(R):
    simd = mkdir('sim'); md = mkdir('sim', 'meshes')
    J, props, origin, links, E = R['J'], R['props'], R['origin'], R['links'], R['E']
    lm = link_meshes(R)
    for lk, m in lm.items():
        write_obj(os.path.join(md, f'{lk}.obj'), m)
    sm = R['sm'].copy(); write_obj(os.path.join(md, 'sts3215.obj'), trimesh.Trimesh(sm.vertices * 1e-3, sm.faces))
    kids = children(J)
    # electronics boxes per link (AABB visuals)
    boxes = {lk: [] for lk in links}
    for e in E:
        b = e['mesh'].bounds; c = (b[0] + b[1]) / 2 - origin[e['link']]; sz = b[1] - b[0]
        boxes[e['link']].append((e['name'], c * 1e-3, sz * 1e-3, e['cat']))
    CC = dict(compute=(0.12, 0.44, 0.88), power=(0.91, 0.44, 0.04), sensor=(0.10, 0.60, 0.33))
    # ---------------- URDF ----------------
    u = ['<?xml version="1.0"?>', '<!-- Budget-22 humanoid. Generated by cad/sim_export.py. Units: m, kg, rad. Link frames are world-aligned at zero pose, origin at the joint shaft. -->',
         '<robot name="budget22">',
         '  <material name="printed"><color rgba="0.78 0.80 0.84 1"/></material>', '  <material name="servo"><color rgba="0.17 0.18 0.21 1"/></material>']
    def link_xml(lk):
        p = props[lk]; I = p['inertia']
        x = [f'  <link name="{lk}">', f'    <inertial><origin xyz="{f(p["com"])}" rpy="0 0 0"/><mass value="{p["mass"]:.6g}"/>',
             f'      <inertia ixx="{I[0][0]:.6g}" ixy="{I[0][1]:.6g}" ixz="{I[0][2]:.6g}" iyy="{I[1][1]:.6g}" iyz="{I[1][2]:.6g}" izz="{I[2][2]:.6g}"/></inertial>',
             f'    <visual><origin xyz="0 0 0" rpy="0 0 0"/><geometry><mesh filename="meshes/{lk}.obj"/></geometry><material name="printed"/></visual>']
        for sv in links[lk]['servos']:
            M = sv.step_to_world(); pos = (M[:3, 3] - origin[lk]) * 1e-3; r, pch, y = rpy_from_R(M[:3, :3])
            x.append(f'    <visual name="{sv.name}_servo"><origin xyz="{f(pos)}" rpy="{f([r, pch, y])}"/><geometry><mesh filename="meshes/sts3215.obj"/></geometry><material name="servo"/></visual>')
        for nm, c, sz, cat in boxes[lk]:
            x.append(f'    <visual name="env_{nm.replace(" ", "_").replace("(", "").replace(")", "").replace("/", "_")}"><origin xyz="{f(c)}"/><geometry><box size="{f(sz)}"/></geometry><material name="m_{cat}"><color rgba="{f(CC[cat])} 1"/></material></visual>')
        if lk.endswith('_foot'):
            # sole collision box (world: x -50..72, y +-28 about plane, z 0..4)
            sole = R['meshes'][lk].bounds
            lo = np.array([-50.0, sole[0][1], 0.0]); hi = np.array([72.0, sole[1][1], 4.0])
            c = ((lo + hi) / 2 - origin[lk]) * 1e-3; sz = (hi - lo) * 1e-3
            x.append(f'    <collision><origin xyz="{f(c)}"/><geometry><box size="{f(sz)}"/></geometry></collision>')
        x.append('  </link>')
        return x
    for lk in links: u += link_xml(lk)
    # imu + camera frames
    u += ['  <link name="imu_link"/>', f'  <joint name="imu_joint" type="fixed"><parent link="base"/><child link="imu_link"/><origin xyz="{f(((-10.0, 0.0, Z_BASE + PT + 2.3) - origin["base"]) * 1e-3)}"/></joint>',
          '  <link name="head_camera_link"/>']
    cam_o = (np.array([XN + 31.0, 0.0, 566.5 + 20.0]) - origin['head']) * 1e-3
    u += [f'  <joint name="head_camera_joint" type="fixed"><parent link="head"/><child link="head_camera_link"/><origin xyz="{f(cam_o)}"/></joint>']
    for j in J:
        sv = j['servo']; lo, hi = j['lim']
        off = (origin[j['child']] - origin[j['parent']]) * 1e-3
        u += [f'  <joint name="{j["name"]}" type="revolute"><!-- servo ID {j["id"]} -->',
              f'    <parent link="{j["parent"]}"/><child link="{j["child"]}"/><origin xyz="{f(off)}" rpy="0 0 0"/><axis xyz="{f(sv.a)}"/>',
              f'    <limit lower="{lo}" upper="{hi}" effort="{STS_EFFORT}" velocity="{STS_VEL}"/><dynamics damping="{DAMP}" friction="{FRIC}"/></joint>']
    u.append('</robot>')
    open(os.path.join(simd, 'budget22.urdf'), 'w').write('\n'.join(u) + '\n')
    # ---------------- MJCF ----------------
    m = ['<mujoco model="budget22">', '  <!-- Budget-22 humanoid. Generated by cad/sim_export.py. Units: m, kg, rad. Actuator/damping/armature values are STARTING values (see sim/README.md). -->',
         '  <compiler angle="radian" meshdir="meshes" autolimits="true"/>', '  <option timestep="0.002" integrator="implicitfast" gravity="0 0 -9.81"/>',
         '  <default>', f'    <joint damping="{DAMP}" armature="{ARM}" frictionloss="{FRIC}"/>',
         f'    <position kp="{KP}" kv="{KV}" forcerange="-{STS_EFFORT} {STS_EFFORT}"/>',
         '    <geom contype="0" conaffinity="0" group="1"/>', '    <default class="foot"><geom contype="1" conaffinity="1" group="0" friction="1.0 0.02 0.001" rgba="0.3 0.3 0.35 1"/></default>', '  </default>',
         '  <asset>', '    <texture name="grid" type="2d" builtin="checker" rgb1=".85 .87 .9" rgb2=".8 .82 .86" width="300" height="300"/>',
         '    <material name="grid" texture="grid" texrepeat="6 6" reflectance="0.05"/>',
         '    <material name="printed" rgba="0.78 0.80 0.84 1"/>', '    <material name="servo" rgba="0.17 0.18 0.21 1"/>',
         '    <mesh name="sts3215" file="sts3215.obj"/>']
    for lk in links: m.append(f'    <mesh name="{lk}" file="{lk}.obj"/>')
    m += ['  </asset>', '  <worldbody>', '    <light pos="0.3 -0.6 1.4" dir="-0.2 0.5 -1" diffuse="0.9 0.9 0.9"/>',
          '    <geom name="floor" type="plane" size="3 3 0.1" material="grid" contype="1" conaffinity="1" group="0"/>']
    def body_xml(lk, ind, off, joint):
        sp = '  ' * ind; p = props[lk]; I = p['inertia']
        x = [f'{sp}<body name="{lk}" pos="{f(off)}">']
        if lk == 'base':
            x.append(f'{sp}  <freejoint name="root"/>')
        else:
            j = joint; x.append(f'{sp}  <joint name="{j["name"]}" type="hinge" axis="{f(j["servo"].a)}" range="{j["lim"][0]} {j["lim"][1]}"/>')
        x.append(f'{sp}  <inertial pos="{f(p["com"])}" mass="{p["mass"]:.6g}" fullinertia="{f(inertia_tuple(np.array(I)))}"/>')
        x.append(f'{sp}  <geom type="mesh" mesh="{lk}" material="printed"/>')
        for sv in links[lk]['servos']:
            M = sv.step_to_world(); pos = (M[:3, 3] - origin[lk]) * 1e-3; q = quat_from_R(M[:3, :3])
            x.append(f'{sp}  <geom name="{sv.name}_servo" type="mesh" mesh="sts3215" pos="{f(pos)}" quat="{f(q)}" material="servo"/>')
        for nm, c, sz, cat in boxes[lk]:
            x.append(f'{sp}  <geom type="box" pos="{f(c)}" size="{f(sz / 2)}" rgba="{f(CC[cat])} 1"/>')
        if lk.endswith('_foot'):
            sole = R['meshes'][lk].bounds
            lo = np.array([-50.0, sole[0][1], 0.0]); hi = np.array([72.0, sole[1][1], 4.0])
            c = ((lo + hi) / 2 - origin[lk]) * 1e-3; sz = (hi - lo) * 1e-3 / 2
            x.append(f'{sp}  <geom name="{lk}_sole" class="foot" type="box" pos="{f(c)}" size="{f(sz)}"/>')
        if lk == 'base':
            x.append(f'{sp}  <site name="imu" pos="{f((np.array([-10.0, 0.0, Z_BASE + PT + 2.3]) - origin["base"]) * 1e-3)}" size="0.004" rgba="0 1 0 1"/>')
        if lk == 'head':
            x.append(f'{sp}  <site name="head_cam_site" pos="{f(cam_o)}" size="0.004" rgba="1 0 0 1"/>')
            x.append(f'{sp}  <camera name="head_cam" pos="{f(cam_o)}" xyaxes="0 -1 0 0 0 1" fovy="66"/>')
        for j in kids.get(lk, []):
            x += body_xml(j['child'], ind + 1, (origin[j['child']] - origin[lk]) * 1e-3, j)
        x.append(f'{sp}</body>')
        return x
    m += body_xml('base', 2, (0, 0, 0.002), None)
    m += ['  </worldbody>', '  <actuator>']
    for j in J:
        m.append(f'    <position name="{j["name"]}" joint="{j["name"]}" ctrlrange="{j["lim"][0]} {j["lim"][1]}"/>  <!-- servo ID {j["id"]} -->')
    m += ['  </actuator>', '  <sensor>', '    <framequat name="imu_quat" objtype="site" objname="imu"/>', '    <gyro name="imu_gyro" site="imu"/>', '    <accelerometer name="imu_acc" site="imu"/>',
          '  </sensor>']
    q0 = ['0 0 0.002', '1 0 0 0'] + ['0'] * len(J)
    m += ['  <keyframe>', f'    <key name="stand" qpos="{" ".join(q0)}" ctrl="{" ".join(["0"] * len(J))}"/>', '  </keyframe>', '</mujoco>']
    open(os.path.join(simd, 'budget22.xml'), 'w').write('\n'.join(m) + '\n')
    # joint map csv
    with open(os.path.join(simd, 'joint_map.csv'), 'w') as fh:
        fh.write('servo_id,joint,parent_link,child_link,axis_x,axis_y,axis_z,lower_rad,upper_rad,nominal_lower,nominal_upper,shaft_x_mm,shaft_y_mm,shaft_z_mm\n')
        for j in sorted(J, key=lambda j: j['id']):
            a = j['servo'].a; S = j['servo'].S; ln = j.get('lim_nom', j['lim'])
            fh.write(f'{j["id"]},{j["name"]},{j["parent"]},{j["child"]},{a[0]:.0f},{a[1]:.0f},{a[2]:.0f},{j["lim"][0]},{j["lim"][1]},{ln[0]},{ln[1]},{S[0]:.1f},{S[1]:.1f},{S[2]:.1f}\n')

def write_gltf(R, path):
    from pygltflib import GLTF2, BufferFormat
    J, E, links, P = R['J'], R['E'], R['links'], R['P']
    sc = trimesh.Scene()
    info = {}
    def col(m, rgba):
        m.visual = trimesh.visual.ColorVisuals(m, face_colors=np.tile(np.array(rgba, np.uint8), (len(m.faces), 1)))
        return m
    palette = ['#9fb3c8', '#a8c5a0', '#c9b8a3', '#b7a6c9', '#c7a6a6', '#a6c4c9']
    def hexrgba(h): return [int(h[i:i + 2], 16) for i in (1, 3, 5)] + [255]
    meshes = R['meshes']
    for i, (k, p) in enumerate(P.items()):
        m = tess_to_mesh(R.get('solids', {}).get(k) or p.build(), 0.25, 0.5)
        col(m, hexrgba('#cfd6df'))
        sc.add_geometry(m, node_name=f'part:{k}', geom_name=f'part:{k}')
        info[f'part:{k}'] = dict(kind='generated', group='printed', name=f'Printed part: {k}', spec='Parametric CadQuery part (generated, FDM-printable). STEP/STL in /cad.', price='filament')
    sm = R['sm']; sm2 = sm.copy(); col(sm2, [40, 44, 52, 255])
    for lk, d in links.items():
        for sv in d['servos']:
            sc.add_geometry(sm2, node_name=f'servo:{sv.name}', geom_name='sts3215', transform=sv.step_to_world())
            info[f'servo:{sv.name}'] = dict(kind='real', group='servo', name=f'Servo ID {sv.id}: {sv.name}', spec='Feetech STS3215. Real vendor STEP (SO-ARM100, Apache-2.0), decimated visual mesh.', price='$19.90')
    CCX = dict(compute='#1f6fe0', power='#e8710a', sensor='#1a9a55')
    for e in E:
        m = e['mesh'].copy(); col(m, hexrgba(CCX[e['cat']]))
        nm = f'env:{e["name"]}'
        sc.add_geometry(m, node_name=nm, geom_name=nm)
        info[nm] = dict(kind=e['kind'], group=e['cat'], name=e['name'], spec=e['spec'], price=e['price'], src=e.get('src', ''))
    glb = sc.export(file_type='glb')
    import tempfile; tmp = os.path.join(tempfile.gettempdir(), 'b22_robot.glb'); open(tmp, 'wb').write(glb)
    g = GLTF2().load(tmp); g.convert_buffers(BufferFormat.DATAURI); g.save(path)
    return info

